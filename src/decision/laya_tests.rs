const TYPES: &[QuestionKind] = &[
    QuestionKind::Choice,
    QuestionKind::Score,
    QuestionKind::Bool,
];

pub(super) fn fixture() -> Value {
    serde_json::from_str(include_str!(
        "../../tests/fixtures/decision/laya_parity.json"
    ))
    .expect("fixture parses")
}

fn published_config() -> Value {
    serde_json::from_str(include_str!(
        "../../tests/fixtures/decision/laya_config.json"
    ))
    .expect("config fixture parses")
}

/// `models/laya` when it holds a complete checkpoint; `None` skips, unless
/// `MLXCEL_REQUIRE_MODELS` is set.
pub(super) fn checkpoint(need_weights: bool) -> Option<PathBuf> {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("models/laya");
    let ready = dir.join("tokenizer.json").is_file()
        && dir.join("config.json").is_file()
        && (!need_weights || dir.join("model.safetensors").is_file());
    if !ready {
        let reason = "models/laya not present (mlxcel download nativ-community/laya)";
        if std::env::var("MLXCEL_REQUIRE_MODELS").is_ok_and(|v| v != "0") {
            panic!("MLXCEL_REQUIRE_MODELS is set: {reason}");
        }
        eprintln!("skipping: {reason}");
    }
    ready.then_some(dir)
}

fn validated(questions: &Value) -> Vec<(String, Question)> {
    validate_questions(
        TYPES,
        &[],
        Some(&json!("state")),
        questions,
        MediaPresence::default(),
    )
    .expect("questions validate")
}

fn one(question: Value) -> Question {
    validated(&json!({ "q": question })).remove(0).1
}

