#[test]
fn batch_ranges_bound_the_padded_size_and_keep_every_row() {
    let row = |len: usize| -> Row { (vec![0; len], vec![1, 2]) };
    let rows = vec![row(4), row(4), row(8), row(2), row(2), row(20)];
    let ranges = batch_ranges(&rows, 16);
    // [4, 4] pads to 8; adding 8 would pad 3 rows to 24 > 16. [8, 2] pads to
    // 16; [2] then [20] alone (longer than the bound, still scored).
    assert_eq!(ranges, [0..2, 2..4, 4..5, 5..6]);
    let covered: Vec<usize> = ranges.into_iter().flatten().collect();
    assert_eq!(covered, (0..rows.len()).collect::<Vec<_>>());
    assert!(batch_ranges(&[], 16).is_empty());
    // The README request (two short rows) stays one batch.
    let readme = batch_ranges(&[row(40), row(30)], MAX_BATCH_TOKENS);
    assert_eq!(readme.len(), 1);
    assert_eq!(readme[0], 0..2);
    assert_eq!(MAX_BATCH_TOKENS / 512, 128);
}

#[test]
fn misshaped_head_tensors_fail_at_load_naming_the_key() {
    let tensor = |shape: &[i32]| {
        let count = shape.iter().product::<i32>() as usize;
        mlxcel_core::from_slice_f32(&vec![0.5; count], shape)
    };
    let width = 64usize;
    let build = |linear1_in: i32| {
        let mut map = mlxcel_core::weights::WeightMap::new();
        let p = "head.layers.0";
        for name in ["query_proj", "key_proj", "value_proj", "out_proj"] {
            map.insert(format!("{p}.attention.{name}.weight"), tensor(&[64, 64]));
            map.insert(format!("{p}.attention.{name}.bias"), tensor(&[64]));
        }
        for name in ["norm1", "norm2"] {
            map.insert(format!("{p}.{name}.weight"), tensor(&[64]));
            map.insert(format!("{p}.{name}.bias"), tensor(&[64]));
        }
        map.insert(format!("{p}.linear1.weight"), tensor(&[128, linear1_in]));
        map.insert(format!("{p}.linear1.bias"), tensor(&[128]));
        map.insert(format!("{p}.linear2.weight"), tensor(&[64, 128]));
        map.insert(format!("{p}.linear2.bias"), tensor(&[64]));
        map.insert("scorer.layers.0.weight".to_string(), tensor(&[64]));
        map.insert("scorer.layers.0.bias".to_string(), tensor(&[64]));
        map.insert("scorer.layers.1.weight".to_string(), tensor(&[64, 64]));
        map.insert("scorer.layers.1.bias".to_string(), tensor(&[64]));
        map.insert("scorer.layers.3.weight".to_string(), tensor(&[2, 64]));
        map.insert("scorer.layers.3.bias".to_string(), tensor(&[2]));
        map
    };
    let good = build(64);
    let w = Weights {
        map: &good,
        family: "laya",
    };
    assert!(DecisionHead::from_weights(&w, "head.layers", 1, width).is_ok());
    let error = MarkerScorer::from_weights(&w, "scorer.layers", width)
        .err()
        .expect("a two-row scorer output is refused")
        .to_string();
    assert!(error.contains("scorer.layers.3.weight"), "{error}");
    let bad = build(32);
    let w = Weights {
        map: &bad,
        family: "laya",
    };
    let error = DecisionHead::from_weights(&w, "head.layers", 1, width)
        .err()
        .expect("a linear1 reading 32 features is refused")
        .to_string();
    assert!(error.contains("head.layers.0.linear1.weight"), "{error}");
}
