#[test]
fn head_sanitize_splits_pytorch_attention_and_sequential_indices() {
    let mut raw = mlxcel_core::weights::WeightMap::new();
    let packed: Vec<f32> = (0..12).map(|v| v as f32).collect();
    let tensor = |values: &[f32], shape: &[i32]| mlxcel_core::from_slice_f32(values, shape);
    raw.insert(
        "head.layers.1.self_attn.in_proj_weight".to_string(),
        tensor(&packed, &[6, 2]),
    );
    raw.insert(
        "head.layers.1.self_attn.out_proj.bias".to_string(),
        tensor(&[1.0], &[1]),
    );
    raw.insert("scorer.3.weight".to_string(), tensor(&[1.0], &[1, 1]));
    raw.insert("act_head.layers.2.bias".to_string(), tensor(&[1.0], &[1]));
    raw.insert(
        "encoder.layers.0.attn.Wqkv.weight".to_string(),
        tensor(&[1.0], &[1, 1]),
    );
    raw.insert(
        "encoder.head.dense.weight".to_string(),
        tensor(&[1.0], &[1, 1]),
    );
    let (encoder, head) = split_weights(raw).expect("splits");
    let keys = |map: &mlxcel_core::weights::WeightMap| {
        let mut keys: Vec<String> = map.keys().cloned().collect();
        keys.sort();
        keys
    };
    assert_eq!(keys(&encoder), ["layers.0.attn.Wqkv.weight"]);
    assert_eq!(
        keys(&head),
        [
            "act_head.layers.2.bias",
            "head.layers.1.attention.key_proj.weight",
            "head.layers.1.attention.out_proj.bias",
            "head.layers.1.attention.query_proj.weight",
            "head.layers.1.attention.value_proj.weight",
            "scorer.layers.3.weight",
        ]
    );
    let key =
        mlxcel_core::utils::array_to_vec_f32(&head["head.layers.1.attention.key_proj.weight"]);
    assert_eq!(key, [4.0, 5.0, 6.0, 7.0]);
    let mut bad = mlxcel_core::weights::WeightMap::new();
    bad.insert(
        "head.layers.0.self_attn.in_proj_bias".to_string(),
        tensor(&[1.0, 2.0], &[2]),
    );
    assert!(sanitize_marker_head(bad, &["scorer"], "laya").is_err());
}

#[test]
fn batches_pad_right_and_mark_missing_options_invalid() {
    let rows = vec![(vec![1, 2, 3, 4], vec![1, 2, 3]), (vec![5, 6], vec![1])];
    let batch = MarkerBatch::pad(&rows, 9).expect("pads");
    assert_eq!((batch.rows, batch.length, batch.options), (2, 4, 3));
    assert_eq!(batch.ids, [1, 2, 3, 4, 5, 6, 9, 9]);
    assert_eq!(batch.attention, [1, 1, 1, 1, 1, 1, 0, 0]);
    assert_eq!(batch.positions, [1, 2, 3, 1, 0, 0]);
    assert_eq!(batch.valid, [true, true, true, true, false, false]);
    assert_eq!(batch.lengths, [4, 2]);
    // The gather reads row-major [B, L, D] at row * L + position.
    let hidden: Vec<f32> = (0..8).map(|v| v as f32).collect();
    let hidden = mlxcel_core::from_slice_f32(&hidden, &[2, 4, 1]);
    let gathered = mlxcel_core::utils::array_to_vec_f32(&batch.gather_markers(&hidden));
    assert_eq!(gathered, [1.0, 2.0, 3.0, 5.0, 4.0, 4.0]);
    let mask =
        mlxcel_core::utils::array_to_vec_f32(&batch.key_padding_mask(mlxcel_core::dtype::FLOAT32));
    assert_eq!(mask[..6], [0.0; 6]);
    assert_eq!(mask[6..], [-1e9, -1e9]);
}

#[test]
fn answers_follow_upstream_shapes() {
    let choice = one(json!({"instructions": "x", "criteria": {"a": null, "b": null, "c": null}}));
    let p = [0.2, 0.7, 0.1];
    let answer = laya_answer(&choice, &p, 0.25).expect("choice");
    let wire = answer.to_json();
    assert_eq!(wire["value"], "b");
    assert_eq!(wire["metadata"]["rl_agent"]["act_probability"], json!(0.25));
    let confidence = (1.0 + p.iter().map(|v: &f64| v * v.ln()).sum::<f64>() / 3f64.ln()) as f32;
    assert!(
        (wire["metadata"]["confidence"].as_f64().expect("conf") - f64::from(confidence)).abs()
            < 1e-4
    );
    assert!((entropy_confidence(&[0.5, 0.5])).abs() < 1e-6);

    let score = one(json!({"type": "score", "instructions": "x", "criteria": ["lo", {"v": 1}]}));
    let Answer::Score {
        value, metadata, ..
    } = laya_answer(&score, &[0.25, 0.75], 0.5).expect("score")
    else {
        panic!("score answer");
    };
    assert_eq!(value, 0.75);
    assert_eq!(metadata["legend"], json!({"0": "lo", "1": {"v": 1}}));
    let keys: Vec<&String> = metadata.keys().collect();
    assert_eq!(keys, ["rl_agent", "confidence", "legend"]);

    let flag = one(json!({"type": "bool", "instructions": "x"}));
    let wire = laya_answer(&flag, &[0.123_44, 0.876_56], 1.0)
        .expect("bool")
        .to_json();
    assert_eq!(wire["value"], true);
    assert_eq!(wire["probability"], json!(0.8766));
    assert!(wire["metadata"].get("confidence").is_none());
}

#[test]
fn request_rows_refuse_a_request_over_the_token_budget() {
    let Some(dir) = checkpoint(false) else {
        return;
    };
    let tokenizer = LayaTokenizer::load(&dir).expect("tokenizer loads");
    let budget = Budget {
        max_len: 512,
        head_max_len: 192,
    };
    let state = tokenizer.encode("refund my charge").expect("state");
    let questions: Value = (0..40)
        .map(|i| {
            (
                format!("q{i}"),
                json!({"type": "bool", "instructions": "Refund?"}),
            )
        })
        .collect::<serde_json::Map<_, _>>()
        .into();
    let questions = validated(&questions);
    let rows = request_rows(&tokenizer, budget, &state, &questions, MAX_REQUEST_TOKENS)
        .expect("fits the default budget");
    assert_eq!(rows.len(), 40);
    let one_row = rows[0].0.len();
    // Every row is the same length here, so a budget of 39 rows refuses.
    let refused = request_rows(&tokenizer, budget, &state, &questions, one_row * 39);
    assert!(
        matches!(&refused, Err(DecisionError::InvalidInput(message)) if message.contains("input tokens in total")),
        "{refused:?}"
    );
    assert!(request_rows(&tokenizer, budget, &state, &questions, one_row * 40).is_ok());
}

