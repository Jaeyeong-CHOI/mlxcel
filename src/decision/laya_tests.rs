#[test]
fn rope_mapping_falls_back_to_existing_keys_then_defaults() {
    let mut config = published_config();
    config["encoder_config"]["rope_parameters"] = json!({"full_attention": {"rope_theta": 5.0}});
    config["encoder_config"]["local_rope_theta"] = json!(7.0);
    let encoder = encoder_config(&config).expect("maps");
    assert_eq!(encoder["global_rope_theta"], json!(5.0));
    assert_eq!(encoder["local_rope_theta"], json!(7.0));
    config["encoder_config"]["rope_parameters"] = json!({});
    config["encoder_config"]
        .as_object_mut()
        .expect("object")
        .remove("local_rope_theta");
    let encoder = encoder_config(&config).expect("maps");
    assert_eq!(encoder["global_rope_theta"], json!(160_000.0));
    assert_eq!(encoder["local_rope_theta"], json!(10_000.0));
    // An absent `rope_parameters` still applies the fallbacks (upstream's
    // `.get("rope_parameters", {})`); without them the local layers would
    // rotate with the global theta.
    let encoder_map = config["encoder_config"].as_object_mut().expect("object");
    encoder_map.remove("rope_parameters");
    encoder_map.remove("global_rope_theta");
    let encoder = encoder_config(&config).expect("maps");
    assert_eq!(encoder["global_rope_theta"], json!(160_000.0));
    assert_eq!(encoder["local_rope_theta"], json!(10_000.0));
    let parsed = LayaConfig::from_config(&config).expect("config parses");
    assert_eq!(parsed.encoder.local_rope_theta, Some(10_000.0));
}

#[test]
fn temperatures_follow_the_bucket_table_then_the_type_and_clamp() {
    let config = LayaConfig::from_config(&published_config()).expect("config parses");
    assert_eq!(
        [1, 2, 3, 5, 6, 10, 11, 40].map(option_bucket),
        ["2", "2", "3-5", "3-5", "6-10", "6-10", "11+", "11+"]
    );
    // `choice:2` from the table; `choice:11+` (0.1006) clamps to 0.5.
    assert_eq!(
        config.temperature(QuestionKind::Choice, 2),
        1.906_356_334_686_279_3_f64 as f32
    );
    assert_eq!(config.temperature(QuestionKind::Choice, 12), 0.5);
    // `score:2` is not in the table: `temperature[1]`.
    assert_eq!(
        config.temperature(QuestionKind::Score, 2),
        1.251_430_034_637_451_2_f64 as f32
    );
    assert_eq!(
        config.temperature(QuestionKind::Bool, 2),
        1.983_399_510_383_606_f64 as f32
    );
    assert_eq!(clamp_temperature(Some(&json!("abc"))), 1.0);
    assert_eq!(clamp_temperature(Some(&json!("2.5"))), 2.5);
    assert_eq!(clamp_temperature(Some(&json!(null))), 1.0);
    assert_eq!(clamp_temperature(Some(&json!("inf"))), 1.0);
    assert_eq!(clamp_temperature(Some(&json!(9))), 5.0);
    assert_eq!(clamp_temperature(None), 1.0);
}

#[test]
fn python_dumps_matches_json_dumps_defaults() {
    let value = json!({"b": [1, 2.5, null, true], "a": "für \"x\"\n", "e": {}, "f": []});
    assert_eq!(
        python_dumps(&value, false),
        r#"{"b": [1, 2.5, null, true], "a": "für \"x\"\n", "e": {}, "f": []}"#
    );
    assert_eq!(
        python_dumps(&json!({"k": "f\u{fc}r \u{1f600}\u{7f}"}), true),
        "{\"k\": \"f\\u00fcr \\ud83d\\ude00\\u007f\"}"
    );
    assert_eq!(python_dumps(&json!(1e-5), false), "1e-05");
    assert_eq!(state_text(Some(&json!("plain"))), "plain");
}

#[test]
fn options_keep_request_order_and_render_like_upstream() {
    let choice = one(json!({
        "type": "choice", "instructions": "x",
        "criteria": {"zeta": null, "alpha": "", "mid": {"n": 1}, "last": "the end"}
    }));
    assert_eq!(
        option_texts(&choice),
        ["zeta", "alpha", r#"mid: {"n": 1}"#, "last: the end"]
    );
    let listed = one(json!({"instructions": "x", "criteria": ["b", "a"]}));
    assert_eq!(option_texts(&listed), ["b", "a"]);
    let score = one(json!({"type": "score", "instructions": "x", "criteria": ["low", 2]}));
    assert_eq!(option_texts(&score), ["level 0: low", "level 1: 2"]);
    let bool_default = one(json!({"type": "noul", "instructions": "x"}));
    assert_eq!(
        option_texts(&bool_default),
        [
            "false: no, the statement does not hold",
            "true: yes, the statement holds"
        ]
    );
    let bool_given = one(json!({
        "type": "bool", "instructions": "x", "criteria": {"true": "yes it is", "false": ""}
    }));
    assert_eq!(
        option_texts(&bool_given),
        ["false: no, the statement does not hold", "true: yes it is"]
    );
    assert_eq!(
        [
            QuestionKind::Choice,
            QuestionKind::Score,
            QuestionKind::Bool
        ]
        .map(qtype),
        [0, 1, 2]
    );
    assert_eq!(type_token(QuestionKind::Bool), "noul");
}

#[test]
fn sequences_match_upstream_ids_and_markers() {
    let Some(dir) = checkpoint(false) else {
        return;
    };
    let tokenizer = LayaTokenizer::load(&dir).expect("tokenizer loads");
    let budget = LayaConfig::from_config(&published_config())
        .expect("config")
        .budget;
    let cases = fixture()["sequences"]
        .as_array()
        .expect("sequences")
        .clone();
    assert!(cases.len() >= 9, "fixture holds every sequence case");
    for case in &cases {
        let name = case["name"].as_str().expect("name");
        let question = one(case["question"].clone());
        let state = tokenizer
            .encode(&state_text(Some(&case["state"])))
            .expect("state encodes");
        let result = sequence(&tokenizer, budget, &state, &question);
        if let Some(message) = case.get("error").and_then(Value::as_str) {
            assert_eq!(
                result,
                Err(DecisionError::InvalidInput(message.to_string())),
                "{name}"
            );
            continue;
        }
        let (ids, markers) = result.unwrap_or_else(|error| panic!("{name}: {error}"));
        let expected_ids: Vec<u32> = serde_json::from_value(case["ids"].clone()).expect("ids");
        let expected_markers: Vec<usize> =
            serde_json::from_value(case["markers"].clone()).expect("markers");
        assert_eq!(ids, expected_ids, "{name}: ids");
        assert_eq!(markers, expected_markers, "{name}: markers");
        for &marker in &markers {
            assert_eq!(ids[marker], tokenizer.mask_id, "{name}: marker token");
        }
    }
    let capped = cases
        .iter()
        .find(|case| case["name"] == "choice_capped")
        .expect("capped case");
    let markers: Vec<usize> = serde_json::from_value(capped["markers"].clone()).expect("m");
    // Twelve options capped at max(4, (192 - 16) // 12) = 14 tokens each.
    assert!(markers.windows(2).all(|pair| pair[1] - pair[0] == 14));
    let long = cases
        .iter()
        .find(|case| case["name"] == "long_state")
        .expect("long case");
    assert_eq!(long["ids"].as_array().map(Vec::len), Some(budget.max_len));
}

